function translateDescription(description) {
  if (ruleTranslations[description]) return ruleTranslations[description];

  let match = /^Exactly "([^"]+)"(?:,.*)?\.?$/.exec(description);
  if (match) return `数字恰好为“${match[1]}”。`;
  match = /^Contains "([^"]+)"(?:\s*\((.*)\))?\.?$/.exec(description);
  if (match) {
    const note = match[2] ? `（${match[2]}）` : "";
    return `数字中包含“${match[1]}”${note}。`;
  }
  match = /^Exactly (.+)\.$/.exec(description);
  if (match) return `数值恰好为 ${match[1]}。`;
  match = /^Ends in (.+)\.$/.exec(description);
  if (match) return `以 ${match[1]} 结尾。`;
  match = /^Divisible only by 1 and itself\.$/.exec(description);
  if (match) return "只能被 1 和自身整除（质数）。";
  match = /^A perfect (.+) power \((.+)\)\.$/.exec(description);
  if (match) return `完全的${match[1]}次幂（${match[2]}）。`;
  match = /^Splits into three or more numbers with a constant ratio(?: other than 1)?\.?$/.exec(description);
  if (match) return "可拆分为三个或更多数字，且这些数字构成等比数列。";
  match = /^Splits into three or more numbers with a constant difference\.$/.exec(description);
  if (match) return "可拆分为三个或更多数字，且这些数字构成等差数列。";
  match = /^An? (.+) number(?: where (.+))?\.$/.exec(description);
  if (match) return `符合“${match[1]}”定义的数字${match[2] ? `：${match[2]}` : ""}。`;
  return `计分条件：${description}`;
}

